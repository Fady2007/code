        // --- Utility Functions for Arabic Search Normalization ---

        // Function to normalize Arabic text (remove tashkeel, unify alef, unify yaa/alef maqsurah, unify ha/ta marbuta)
      function normalizeArabic(text) {
            if (!text) return "";
            text = text.toString();
            
            // إزالة التشكيل
            text = text.replace(/[\u064B-\u065F\u0670]/g, "");

            // توحيد الألف (أ، إ، آ -> ا)
            text = text.replace(/[أإآ]/g, "ا");

            // توحيد الياء (ى -> ي)
            text = text.replace(/ى/g, "ي");

            // (تحديث هام) توحيد الياء الفارسية لياء عربية (ی -> ي)
            text = text.replace(/ی/g, "ي");

            // توحيد التاء المربوطة والهاء (ة -> ه)
            text = text.replace(/ة/g, "ه");

            return text;
        }

