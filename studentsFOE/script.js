        function searchData() {
            const rawInput = document.getElementById('searchInput').value.trim();
            const table = document.getElementById('resultsTable');
            const tableBody = document.getElementById('tableBody');
            const noResults = document.getElementById('noResults');
            const stats = document.getElementById('stats');

            // Clear previous results
            tableBody.innerHTML = '';
            table.style.display = 'none';
            noResults.style.display = 'none';
            stats.innerHTML = '';

            if (rawInput === "") {
                return;
            }

            // Normalize the search input
            const normalizedInput = normalizeArabic(rawInput).toLowerCase();

            // Filter logic
            const results = students.filter(student => {
                // Normalize student name
                const normalizedName = normalizeArabic(student.name).toLowerCase();
                
                // Check exact ID match or Partial Name match (using normalized strings)
                return student.id.includes(rawInput) || normalizedName.includes(normalizedInput);
            });

            if (results.length > 0) {
                results.forEach(student => {
                    const row = document.createElement('tr');
                    
                    const nameCell = document.createElement('td');
                    nameCell.textContent = student.name;
                    
                    const idCell = document.createElement('td');
                    idCell.textContent = student.id;
                    idCell.style.textAlign = 'center';
                    idCell.style.direction = 'ltr'; // Ensure numbers don't flip in bad ways

                    row.appendChild(nameCell);
                    row.appendChild(idCell);
                    tableBody.appendChild(row);
                });
                
                table.style.display = 'table';
                stats.textContent = `تم العثور على ${results.length} نتيجة`;
            } else {
                noResults.style.display = 'block';
            }
        }